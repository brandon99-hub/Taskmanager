export function generateCompletePDF(data: any, filename: string): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ size: 'A4', margin: 50, bufferPages: true, autoFirstPage: false });
      const chunks: Buffer[] = [];
      doc.on('data', (chunk: Buffer) => chunks.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', reject);

      let pageNumber = 0;
      const addNewPage = () => { doc.addPage(); pageNumber++; addBrandedHeader(doc, 'Complete Report', 50); addBrandedFooter(doc, pageNumber); return 115; };

      let currentY = addNewPage();

      doc.fontSize(14).fillColor('#1F4E79').font('Helvetica-Bold').text('Executive Summary', 50, currentY);
      currentY += 30;

      const projects = data.projects || [];
      const milestones = data.milestones || [];
      const performance = data.performance || [];

      doc.fontSize(10).fillColor('#000000').font('Helvetica');
      doc.text(`Total Projects: ${projects.length}`, 50, currentY);
      doc.text(`Total Milestones: ${milestones.length}`, 200, currentY);
      doc.text(`Teams: ${performance.length}`, 350, currentY);
      currentY += 40;

      if (projects.length > 0) {
        doc.fontSize(12).fillColor('#1F4E79').font('Helvetica-Bold').text('Projects Overview', 50, currentY);
        currentY += 25;

        projects.slice(0, 10).forEach((project: any) => {
          if (currentY + 30 > 720) currentY = addNewPage();
          doc.fontSize(9).fillColor('#000000').font('Helvetica');
          doc.text(`• ${project['Project Name'] || 'N/A'} - ${project['Status'] || 'N/A'} (${project['Progress (%)'] || 0}%)`, 58, currentY);
          currentY += 15;
        });
        currentY += 20;
      }

      doc.end();
    } catch (error) { reject(error); }
  });
}

export async function generatePDFBuffer(options: PDFExportOptions): Promise<Buffer> {
  const { data, reportType, filename } = options;

  switch (reportType) {
    case 'projects':
      return generateProjectSummaryPDF(data, filename);
    case 'milestones':
      return generateMilestonesPDF(data, filename);
    case 'performance':
      return generatePerformancePDF(data, filename);
    case 'workload':
      return generateWorkloadPDF(data, filename);
    case 'tickets':
      return generateTicketsPDF(data, filename);
    case 'complete':
      return generateCompletePDF(data, filename);
    default:
      throw new Error(`PDF generation not implemented for report type: ${reportType}`);
  }
}
