import PDFDocument from 'pdfkit';
import * as fs from 'fs';
import * as path from 'path';

interface PDFExportOptions {
  filename: string;
  data: any;
  reportType: string;
}

const LOGO_PATH = path.join(__dirname, '../../client/public/logo.png');
const COMPANY_NAME = 'Ecorenet Business Solutions Limited';

/**
 * Shared branded header/footer, used by every report generator below. Consolidates what used
 * to be 6 near-identical closures (logo + title + timestamp + rule line) into one place, so
 * the branding only needs to be right once.
 */
function addBrandedHeader(doc: PDFKit.PDFDocument, title: string, logoSize = 40) {
  if (fs.existsSync(LOGO_PATH)) {
    doc.image(LOGO_PATH, 40, 28, { width: logoSize });
  }

  doc.fontSize(16)
     .fillColor('#1F4E79')
     .font('Helvetica-Bold')
     .text(COMPANY_NAME, 40 + logoSize + 12, 30);

  doc.fontSize(13)
     .fillColor('#333333')
     .font('Helvetica-Bold')
     .text(title, 40 + logoSize + 12, 50);

  doc.fontSize(8)
     .fillColor('#666666')
     .font('Helvetica')
     .text(`Generated: ${new Date().toLocaleDateString()} ${new Date().toLocaleTimeString()}`, 40 + logoSize + 12, 68);

  doc.moveTo(40, 90)
     .lineTo(555, 90)
     .strokeColor('#4472C4')
     .lineWidth(1.5)
     .stroke();
}

function addBrandedFooter(doc: PDFKit.PDFDocument, pageNumber: number) {
  doc.fontSize(8)
     .fillColor('#999999')
     .font('Helvetica')
     .text(`Page ${pageNumber} - ${COMPANY_NAME} - Generated by TaskFlow`, 40, 770, { align: 'center', width: 515 });
}

export function generateProjectSummaryPDF(data: any, filename: string): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        size: 'A4',
        margin: 50,
        bufferPages: true,
        autoFirstPage: false
      });

      const chunks: Buffer[] = [];

      doc.on('data', (chunk: Buffer) => chunks.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', reject);

      const { projects = [], milestones = [] } = data;

      let pageNumber = 0;

      const addNewPage = () => {
        doc.addPage();
        pageNumber++;
        addBrandedHeader(doc, 'Project Summary Report', 50);
        addBrandedFooter(doc, pageNumber);
        return 115;
      };

      let currentY = addNewPage();

      const totalProjects = projects.length;
      const activeProjects = projects.filter((p: any) =>
        p.Status !== 'completed' && p.Status !== 'cancelled'
      ).length;
      const completedProjects = projects.filter((p: any) => p.Status === 'completed').length;
      const avgProgress = totalProjects > 0
        ? Math.round(projects.reduce((sum: number, p: any) => sum + (parseInt(p['Progress (%)']) || 0), 0) / totalProjects)
        : 0;

      doc.fontSize(10)
         .fillColor('#666666')
         .font('Helvetica')
         .text(`Total Projects: ${totalProjects} | Active: ${activeProjects} | Completed: ${completedProjects} | Avg Progress: ${avgProgress}%`, 50, currentY, { align: 'center', width: 495 });

      currentY += 25;

      const tableHeaderHeight = 30;
      const projectRowHeight = 28;
      const milestoneRowHeight = 26;

      doc.rect(50, currentY, 495, tableHeaderHeight)
         .fillAndStroke('#E8E8E8', '#AAAAAA')
         .lineWidth(1.5);

      doc.fillColor('#1a1a1a')
         .fontSize(9)
         .font('Helvetica-Bold')
         .text('Project / Milestone', 58, currentY + 10, { width: 132 });
      doc.text('Type', 195, currentY + 10, { width: 40, align: 'center' });
      doc.text('Status', 240, currentY + 10, { width: 45, align: 'center' });
      doc.text('Progress', 285, currentY + 10, { width: 33, align: 'center' });
      doc.text('Budget/Fee', 323, currentY + 10, { width: 52, align: 'right' });
      doc.text('Days', 380, currentY + 10, { width: 30, align: 'center' });
      doc.text('Start', 415, currentY + 10, { width: 38, align: 'center' });
      doc.text('End', 458, currentY + 10, { width: 38, align: 'center' });
      doc.text('Manager', 501, currentY + 10, { width: 39, align: 'center' });

      currentY += tableHeaderHeight;

      if (projects.length === 0) {
        doc.rect(50, currentY, 495, projectRowHeight)
           .fillAndStroke('#FFFFFF', '#E5E5E5')
           .lineWidth(0.5);

        doc.fontSize(10)
           .fillColor('#999999')
           .font('Helvetica-Oblique')
           .text('No projects available', 58, currentY + 10, { align: 'center', width: 485 });

        currentY += projectRowHeight;
      } else {
        const calculateDuration = (startDate: string, endDate: string): string => {
          if (!startDate || startDate === 'N/A' || !endDate || endDate === 'N/A') return '-';
          try {
            const start = new Date(startDate);
            const end = new Date(endDate);
            const diffTime = Math.abs(end.getTime() - start.getTime());
            const diffDays = Math.ceil(diffTime / (1000 * 60 * 60 * 24));
            return `${diffDays}d`;
          } catch {
            return '-';
          }
        };

        projects.forEach((project: any, projectIndex: number) => {
          const projectName = project['Project Name'];
          const projectMilestones = milestones.filter((m: any) =>
            m.Client === project['Client'] && m['_projectName'] === projectName
          );

          if (currentY + projectRowHeight > 720) {
            currentY = addNewPage();
          }

          const projectBg = '#F8F9FA';
          doc.rect(50, currentY, 495, projectRowHeight)
             .fillAndStroke(projectBg, '#D0D0D0')
             .lineWidth(1);

          doc.fillColor('#000000')
             .fontSize(9)
             .font('Helvetica-Bold')
             .text(project['Project Name'], 58, currentY + 10, { width: 132, ellipsis: true });

          doc.fillColor('#666666')
             .fontSize(8)
             .font('Helvetica-Bold')
             .text('PROJECT', 195, currentY + 10, { width: 40, align: 'center' });

          doc.fillColor('#444444')
             .fontSize(8)
             .font('Helvetica')
             .text(project.Status ? project.Status.toUpperCase() : 'N/A', 240, currentY + 10, { width: 45, align: 'center' });

          const projectProgress = project['Progress (%)'];
          const progressValue = projectProgress !== undefined && projectProgress !== null ? Math.round(projectProgress) : 0;
          doc.text(`${progressValue}%`, 285, currentY + 10, { width: 33, align: 'center' });

          const budget = project['Budget (KSh)'] || '0';
          const budgetNum = typeof budget === 'string' ? parseFloat(budget.replace(/,/g, '')) : budget;
          doc.text(budgetNum ? budgetNum.toLocaleString() : '0', 323, currentY + 10, { width: 52, align: 'right' });

          const duration = calculateDuration(project['Start Date'], project['End Date']);
          doc.text(duration, 380, currentY + 10, { width: 30, align: 'center' });
          doc.text(project['Start Date'] || 'N/A', 415, currentY + 10, { width: 38, align: 'center' });
          doc.text(project['End Date'] || 'N/A', 458, currentY + 10, { width: 38, align: 'center' });
          doc.text(project.Manager || 'N/A', 501, currentY + 10, { width: 39, ellipsis: true });

          currentY += projectRowHeight;

          if (projectMilestones.length > 0) {
            projectMilestones.forEach((milestone: any, mIndex: number) => {
              if (currentY + milestoneRowHeight > 720) {
                currentY = addNewPage();
              }

              const milestoneBg = mIndex % 2 === 0 ? '#FFFFFF' : '#F8F8F8';
              doc.rect(50, currentY, 495, milestoneRowHeight)
                 .fillAndStroke(milestoneBg, '#DDDDDD')
                 .lineWidth(0.5);

              const statusColors: Record<string, string> = {
                'done': '#28A745',
                'finished': '#28A745',
                'completed': '#28A745',
                'in_progress': '#4472C4',
                'ongoing': '#4472C4',
                'fc_review': '#4472C4',
                'started': '#FFA500',
                'overdue': '#DC3545',
                'delayed': '#DC3545',
                'on_hold': '#6C757D',
                'cancelled': '#6C757D',
                'todo': '#999999',
                'not started': '#999999',
                'not_started': '#999999'
              };

              const milestoneStatus = (milestone.Status || 'not_started').toLowerCase().replace(/ /g, '_');
              const statusColor = statusColors[milestoneStatus] || '#999999';

              doc.fontSize(10)
                 .fillColor(statusColor)
                 .font('Helvetica')
                 .text('●', 63, currentY + 9);

              doc.fillColor('#2C2C2C')
                 .fontSize(8)
                 .font('Helvetica')
                 .text(milestone['Milestone Name'], 73, currentY + 9, { width: 117, ellipsis: true });

              doc.fillColor('#777777')
                 .fontSize(7)
                 .text('Milestone', 195, currentY + 9, { width: 40, align: 'center' });

              doc.fillColor('#555555')
                 .fontSize(8)
                 .text(milestone.Status || 'not_started', 240, currentY + 9, { width: 45, align: 'center' });

              const milestoneProgress = milestone['Progress (%)'];
              const milestoneProgressValue = milestoneProgress !== undefined && milestoneProgress !== null ? Math.round(milestoneProgress) : 0;
              doc.text(`${milestoneProgressValue}%`, 285, currentY + 9, { width: 33, align: 'center' });

              const fee = milestone['Fee Amount (KSh)'] || '0';
              const feeNum = typeof fee === 'string' ? parseFloat(fee.replace(/,/g, '')) : fee;
              doc.text(feeNum ? feeNum.toLocaleString() : '0', 323, currentY + 9, { width: 52, align: 'right' });

              const milestoneDuration = calculateDuration(milestone['Start Date'], milestone['Due Date'] || milestone['End Date']);
              doc.text(milestoneDuration, 380, currentY + 9, { width: 30, align: 'center' });
              doc.text(milestone['Start Date'] || 'N/A', 415, currentY + 9, { width: 38, align: 'center' });
              doc.text(milestone['Due Date'] || milestone['End Date'] || 'N/A', 458, currentY + 9, { width: 38, align: 'center' });
              doc.text(milestone['Assigned User'] || 'Unassigned', 501, currentY + 9, { width: 39, ellipsis: true });

              currentY += milestoneRowHeight;
            });
          }
        });
      }

      doc.end();
    } catch (error) {
      reject(error);
    }
  });
}

export function generateMilestonesPDF(data: any, filename: string): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ size: 'A4', margin: 40, bufferPages: true, autoFirstPage: false });
      const chunks: Buffer[] = [];
      doc.on('data', (chunk: Buffer) => chunks.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', reject);

      let pageNumber = 0;
      const addNewPage = () => { doc.addPage(); pageNumber++; addBrandedHeader(doc, 'Milestones Report'); addBrandedFooter(doc, pageNumber); return 105; };

      let currentY = addNewPage();
      const milestones = Array.isArray(data) ? data : [];

      const tableHeaders = ['Project', 'Milestone Name', 'Manager', 'Progress', 'Billing Status', 'Fee (KSh)', 'Start Date', 'Due Date'];
      const colWidths = [80, 100, 80, 50, 70, 60, 60, 60];
      const tableWidth = colWidths.reduce((sum, width) => sum + width, 0);
      const startX = 40;

      doc.rect(startX, currentY, tableWidth, 25).fillAndStroke('#E8E8E8', '#AAAAAA');
      let xPos = startX;
      tableHeaders.forEach((header, i) => {
        doc.fillColor('#1a1a1a').fontSize(8).font('Helvetica-Bold');
        doc.text(header, xPos + 3, currentY + 8, { width: colWidths[i] - 6, ellipsis: true });
        xPos += colWidths[i];
      });
      currentY += 25;

      milestones.forEach((milestone: any, index: number) => {
        if (currentY + 20 > 750) currentY = addNewPage();

        const rowBg = index % 2 === 0 ? '#FFFFFF' : '#F8F8F8';
        doc.rect(startX, currentY, tableWidth, 20).fillAndStroke(rowBg, '#E5E5E5').lineWidth(0.5);

        xPos = startX;
        const rowData = [
          milestone['Project Name'] || 'N/A',
          milestone['Milestone Name'] || 'N/A',
          milestone['Manager'] || 'Not assigned',
          `${milestone['Progress (%)'] || 0}%`,
          milestone['Billing Status'] || 'none',
          milestone['Fee Amount (KSh)'] || '0',
          milestone['Start Date'] || 'N/A',
          milestone['Due Date'] || 'N/A'
        ];

        rowData.forEach((cellData, i) => {
          doc.fillColor('#2C2C2C').fontSize(7).font('Helvetica');
          doc.text(String(cellData), xPos + 3, currentY + 6, { width: colWidths[i] - 6, ellipsis: true });
          xPos += colWidths[i];
        });
        currentY += 20;
      });

      doc.end();
    } catch (error) { reject(error); }
  });
}

